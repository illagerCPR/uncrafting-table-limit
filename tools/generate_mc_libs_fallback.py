"""Generate gradle/mc-libs-fallback.gradle from the cached minecraft-dependencies metadata.

Why this exists: ModDevGradle asks for the Minecraft game libraries through the
`net.neoforged:minecraft-dependencies` module. That module publishes its libraries in
variants keyed by attributes (`net.neoforged.distribution`, `org.gradle.category`). When the
module metadata cannot be fetched from the NeoForge repository, Gradle falls back to the
module's dependency-free `platformDependencies` variant, the compile classpath silently loses
`com.mojang:brigadier` and friends, and compilation fails with "cannot access Message".

The generated file restates those libraries as plain dependencies. It is only applied with
`-PmcLibsFallback=true` (see build.gradle); CI resolves them the normal way.

Usage:
    python3 tools/generate_mc_libs_fallback.py

The metadata is read from the local Gradle cache, so it must be run on a machine that has
resolved the NeoForge toolchain at least once.
"""

import json
import pathlib
import sys
from glob import glob

CACHE = pathlib.Path.home() / ".gradle/caches/modules-2/files-2.1/net.neoforged/minecraft-dependencies"
OUTPUT = pathlib.Path("gradle/mc-libs-fallback.gradle")

HEADER = """// GENERATED by tools/generate_mc_libs_fallback.py - do not edit by hand.
//
// Why: ModDevGradle asks for the Minecraft game libraries through the
// net.neoforged:minecraft-dependencies module. When that module's Gradle module metadata
// cannot be obtained with the expected variant attributes, Gradle silently falls back to
// its dependency-free 'platformDependencies' variant and the compile classpath ends up
// without com.mojang:brigadier and friends. This file restates those libraries explicitly
// so a build still succeeds on networks where the NeoForge repository is unreachable.
//
// It is only applied with -PmcLibsFallback=true (see build.gradle); CI resolves the
// libraries the normal way through the module metadata.
//
// The same runtime entries are also exposed through the `mcGameLibs` configuration, which
// build.gradle uses to append the libraries to ModDevGradle's legacyClasspath files (the
// game layer of a dev run is built from that file, not from the java -cp argument).
configurations {
    mcGameLibs
}

dependencies {"""


def find_metadata() -> pathlib.Path:
    candidates = sorted(glob(str(CACHE / "*" / "*" / "minecraft-dependencies-*.module")))
    if not candidates:
        sys.exit(f"no minecraft-dependencies module metadata under {CACHE}")
    return pathlib.Path(candidates[-1])


def coordinates(module: dict, variant: str) -> set:
    for entry in module["variants"]:
        if entry["name"] != variant:
            continue
        result = set()
        for dependency in entry.get("dependencies", []):
            version = dependency.get("version", {})
            version = version.get("strictly") or version.get("requires") or version.get("prefers")
            coordinate = f"{dependency['group']}:{dependency['module']}:{version}"
            # Some artifacts only publish classifier jars (netty epoll natives, LWJGL natives);
            # the classifier lives in a thirdPartyCompatibility artifactSelector.
            selector = dependency.get("thirdPartyCompatibility", {}).get("artifactSelector", {})
            classifier = selector.get("classifier")
            if classifier:
                coordinate += f":{classifier}"
            result.add(coordinate)
        return result
    return set()


def main() -> None:
    path = find_metadata()
    module = json.loads(path.read_text())
    compile_deps = sorted(coordinates(module, "clientCompileDependencies") | coordinates(module, "serverCompileDependencies"))
    runtime_deps = sorted(coordinates(module, "clientRuntimeDependencies") | coordinates(module, "serverRuntimeDependencies"))
    linux_natives = sorted(coordinates(module, "clientLinuxNatives"))

    lines = [HEADER, "    // Minecraft game libraries, compile + runtime"]
    lines += [f'    compileOnly "{dep}"' for dep in compile_deps]
    lines += [f'    runtimeOnly "{dep}"' for dep in runtime_deps]
    lines += ["", "    // Same set exposed for the legacyClasspath hook in build.gradle"]
    lines += [f'    mcGameLibs "{dep}"' for dep in runtime_deps]
    lines += ["", "    // Linux natives (client runs on this machine)"]
    lines += [f'    runtimeOnly "{dep}"' for dep in linux_natives]
    lines += [f'    mcGameLibs "{dep}"' for dep in linux_natives]
    lines += ["}", ""]

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines))
    print(f"wrote {OUTPUT}: compile={len(compile_deps)} runtime={len(runtime_deps)} natives={len(linux_natives)}")


if __name__ == "__main__":
    main()
